function injectCustomPrompt(base) {
let result = base;
if (state.customPrompt) result += `\n\n【用户偏好附加指令】\n${state.customPrompt}`;
if (state.glossary) {
result += `\n\n【强制术语表 Glossary — 以下词汇必须按对应关系翻译，不得偏离】\n${state.glossary}`;
}
return result;
}


